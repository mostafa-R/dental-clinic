const fs = require('fs');
function ensureKeys(path, entries){
  let s = fs.readFileSync(path, 'utf8');
  const toAdd = entries.filter(([k]) => !s.includes("'" + k + "'") && !s.includes('"' + k + '"'));
  if (!toAdd.length) { console.log(path, 'nochange'); return; }
  const block = '\n' + toAdd.map(([k,v]) => `    '${k}': ${JSON.stringify(v)},`).join('\n') + '\n';
  const idx = s.lastIndexOf('};');
  if (idx !== -1) s = s.slice(0, idx) + block + s.slice(idx);
  fs.writeFileSync(path, s, 'utf8');
  console.log(path, 'added', toAdd.length);
}

